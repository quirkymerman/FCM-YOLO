class EVC(nn.Module):
    """Explicit Visual Center模块，用于捕获全局和局部特征"""

    def __init__(self, c1, c2=256, n=64):
        """
        参数:
            c1: 输入通道数
            c2: 基础通道数(默认256)
            k: 视觉中心数量(默认64)
        """
        super().__init__()
        self.c2 = c2
        self.k = n

        # Stem块 - 特征预处理
        self.stem = nn.Sequential(
            Conv(c1, c2, 7, 1),  # 7x7卷积扩大感受野
        )

        # 轻量级MLP分支 - 捕获全局依赖
        self.mlp = nn.Sequential(
            DWConv(c2, c2, 3, 1),  # 深度可分离卷积(3x3)
            Conv(c2, c2 // 2, 1),  # 1x1卷积进行通道缩减
            nn.Conv2d(c2 // 2, c2, kernel_size=1)  # 1x1卷积进行通道扩展
        )
        self.scale = nn.Parameter(torch.ones(1))  # 可学习缩放参数
        self.dropout = nn.Dropout(0.1)  # Dropout层

        # 可学习视觉中心(LVC)分支 - 捕获局部关键区域
        self.lvc_conv = Conv(c2, n, k=1, act=False)  # 生成n个视觉中心
        self.proj = Conv(n, c2, k=1)  # 将视觉中心特征投影回原空间

    def forward(self, x):
        # 1. Stem处理
        x = self.stem(x)

        # 2. MLP分支处理
        x_mlp = self.mlp(x)
        x_mlp = x + self.dropout(self.scale * x_mlp)  # 残差连接


        # LVC branch
        attn = self.lvc_conv(x).softmax(dim=1)  # [B, k, H, W]
        x_lvc = (x.unsqueeze(1) * attn.unsqueeze(2)).sum(dim=(3, 4))  # [B, k, C]
        x_lvc = self.proj(x_lvc.permute(0, 2, 1).unsqueeze(-1))  # [B, C, k, 1]

        # Concatenate features
        return torch.cat([x_mlp, x_lvc.expand(-1, -1, -1, x.size(-1))], dim=1)



class ChannelMLPBlock(nn.Module):
    """
    通道 MLP：1×1 卷积 → ReLU → 1×1 卷积，包含残差连接。
    扩展因子 e。
    """

    def __init__(self, c1, c2, e=4, drop_path=0.0):
        """
        Args:
            c1 (int): Number of input channels.
            c2 (int): Number of output channels.
            e (float): Channel expansion ratio for hidden channels.
        """
        super().__init__()
        c_ = int(c1 * e)
        self.norm = nn.GroupNorm(32, c1)
        self.fc1 = Conv(c1, c_, k=1, s=1)
        self.act = nn.ReLU()
        self.fc2 = Conv(c_, c2, k=1, s=1)
        self.drop = nn.Dropout(drop_path) if drop_path > 0 else nn.Identity()

    def forward(self, x):
        out = self.norm(x)
        out = self.fc2(self.act(self.fc1(out)))
        out = self.drop(out)
        return x + out


