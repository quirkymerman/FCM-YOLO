class MKP(nn.Module):
    def __init__(self, c1, c2):
        """
        Initialize MKP(Multi-Kernel Perception) Unit.
        Args:
            c1 (int): Input channels
            c2 (int): Output channels.
        """
        super().__init__()
        c2 = c1
        self.cv0 = DWConv(c1, c1, 3, 1)
        self.cv1 = Conv(c1, c1, 1, 1)
        self.cv2 = DWConv(c1, c1, 5, 1)
        self.cv3 = Conv(c1, c1, 1, 1)
        self.cv4 = DWConv(c1, c1, 7,1)
        self.cv5 = Conv(c1, c2, 1,1)

    def forward(self, x):
        """Forward MKP"""

        return  self.cv5(self.cv4(self.cv3(self.cv2(self.cv1(self.cv0(x))))))

