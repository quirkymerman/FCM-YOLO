class CDCASPPF(nn.Module):
    def __init__(self, c1, c2):
        """
        Initializes the CDCSPPF4.0 layer with given input/output channels and kernel size.
        Modified version replaces maxpool with dilated convolutions
        """
        super().__init__()
        c_ = c1 // 2  # hidden channels
        self.cv1 = Conv(c1, c_, 1, 1)
        self.cv2 = Conv(c_ * 4 , c2, 1, 1)
        # Replace maxpool with dilated convs (dilation=1,3,5)
        self.m = nn.ModuleList([
            Conv(c_, c_,k=3, s=1, d=d)
            for d in [1, 3, 5]
        ])
        self.eca = ECA(c_)
        # self.cbam = CBAM(c_)
        # self.ca = CoordAtt(c_)

    def forward(self, x):
        """Forward pass through modified CDCSPPF layer."""
        x = self.cv1(x)
        y = self.eca(x)

        # 扩张卷积分支处理
        y1 = [y]
        y1.extend(m(y1[-1]) for m in self.m)

        # 合并两个分支
        return self.cv2(torch.cat([x,y1[0],y1[1],y1[3]], 1))

