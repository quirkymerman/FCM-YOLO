class CAA(nn.Module):
    """Context Anchor Attention module"""

    def __init__(self, c1, h_kernel_size=9, v_kernel_size=9):
        super().__init__()
        self.avg_pool = nn.AvgPool2d(7, 1, 3)
        self.cv1 = Conv(c1, c1, 1, 1,)
        self.h_conv = nn.Conv2d(c1, c1, (1, h_kernel_size), 1,
                                (0, h_kernel_size // 2), groups=c1, bias=False)
        self.v_conv = nn.Conv2d(c1, c1, (v_kernel_size, 1), 1,
                                (v_kernel_size // 2, 0), groups=c1, bias=False)
        self.conv2 = Conv(c1, c1, 1, 1)
        self.act = nn.Sigmoid()
    def forward(self, x):
        """Forward pass through CAA module."""
        y = self.act(self.conv2(self.v_conv(self.h_conv(self.cv1(self.avg_pool(x))))))

        return y


class PKI_Block(nn.Module):
    def __init__(self, c1):
        """
        Initialize PKI_Block module.

        Args:
            c1 (int): Input channels
            c2 (int, optional): Output channels.

        """
        super().__init__()
        self.cv1 = DWConv(c1, c1, 3, 1)
        self.cv2 = Conv(c1, c1, 1, 1)

        # Multi-Scale branch
        self.context_convs = nn.ModuleList([
            DWConvNoBN(c1, c1, k) for k in [1, 3, 5]
        ])

    def forward(self, x):
        """Forward pass through OSF module."""
        y = self.cv1(x)
        # Context branch
        context = [conv(y) for conv in self.context_convs]
        return self.cv2(y + sum(context))

class PKI_Module(nn.Module):
    def __init__(self, c1, c2):
        """
        Initialize PKI_Module.
        Args:
            c1 (int): Input channels
            c2 (int, optional): Output channels.
        """
        super().__init__()
        self.caa = CAA(c1)
        self.pki = PKI_Block(c1)
        self.cv = Conv(c1, c2, 1)

    def forward(self, x):
        """Forward pass through PKI module."""
        caa = self.caa(x)
        # PKI_Block分支处理
        pki = self.pki(x)

        return self.cv(caa * pki + pki)

class PKI(nn.Module):
    def __init__(self, c1, c2, e=0.5):
        """
        Initialize PKI module.

        Args:
            c1 (int): Input channels
            c2 (int, optional): Output channels.
            c_ (int): hidden channels
            e (float): Expansion ratio for hidden channels
        """
        super().__init__()
        c_ = int(c1 * e)
        self.cv0 = Conv(c1, c_ * 2, 1)
        self.cv1 = Conv(c_ * 2, c2, 1)
        self.pki_m = PKI_Module(c_, c_)
        self.ffn = nn.Sequential(Conv(c_, c_ * 2, 1), Conv(c_ * 2, c_, 1, act=False))


    def forward(self, x):
        """Forward pass through PKI."""
        y = self.cv0(x)
        # 将特征图分成两部分
        y1, y2 = y.chunk(2, dim=1)

        y1 = self.pki_m(y1)
        y2 = self.ffn(y2)
        # 拼接并输出
        return self.cv1(torch.cat([y1, y2], dim=1))

