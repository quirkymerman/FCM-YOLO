class MAA_Block(nn.Module):
    def __init__(self, c1):
        """
        Initialize MAA_Block module.
        Args:
            c1 (int): Input channels
        """
        super().__init__()
        # 双分支点卷积
        self.cv0 = Conv(c1, c1, 1, 1)
        self.cv1 = Conv(c1, c1, 1, 1)

        # Multi-Scale DWConv branch
        self.dwcv1 = DWConv(c1 // 4, c1 // 4, k=1)
        self.dwcv3 = DWConv(c1 // 4, c1 // 4, k=3)
        self.dwcv5 = DWConv(c1 // 4, c1 // 4, k=5)

        # 融合卷积
        self.fcv = Conv(c1, c1, 1, 1)
        self.cv2 = Conv(2 * c1 ,c1, 1, 1)

    def forward(self, x):
        """Forward pass through MAA_Block."""
        # 双分支点卷积
        u1 = self.cv0(x)
        u2 = self.cv1(x)

        # 将u1沿通道分成4份
        u11, u12, u13, u14 = torch.chunk(u1, 4, dim=1)

        # 多尺度处理前三个子图
        v11 = self.dwcv1(u11)
        v12 = self.dwcv3(u12)
        v13 = self.dwcv5(u13)
        # 拼接并融合
        v = self.fcv(torch.cat([v11, v12, v13, u14], dim=1))

        # 最终输出
        return self.cv2(torch.cat([v, u2], dim=1))


class CMAA_Block(nn.Module):
    def __init__(self, c1):
        """
        Initialize MAA_Block module.
        Args:
            c1 (int): Input channels
        """
        super().__init__()
        # 双分支点卷积
        self.cv0 = Conv(c1, c1, 1, 1)
        self.cv1 = Conv(c1, c1, 1, 1)

        # Multi-Scale DWConv branch
        self.m = nn.ModuleList([
            DWConvNoBN(c1, c1, k) for k in [1, 3, 3]
        ])

        # 融合卷积
        self.fcv = Conv(c1 * 4, c1 * 4, 1, 1)
        self.cv2 = Conv(c1 * 5 ,c1, 1, 1)

    def forward(self, x):
        """Forward pass through MAA_Block."""
        # 双分支点卷积
        y1 = [self.cv0(x)]
        y2 = self.cv1(x)

        # Multi-Scale branch
        y1.extend(m(y1[-1]) for m in self.m)
        # 拼接并融合
        y1 = self.fcv(torch.cat(y1[:], dim=1))
        # 最终输出
        return self.cv2(torch.cat([y1, y2], dim=1))


